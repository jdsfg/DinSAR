#!/usr/bin/env python3
"""Generate SNAPHU configuration values from a GMTSAR PRM."""

import argparse
import json
import math
import re
import sys
from pathlib import Path


C = 299792458.0
PRM_LINE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*([^\s#]+)")
CONF_LINE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*(?:=|\s+)")


def read_prm(path):
    values = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        match = PRM_LINE.match(line)
        if match:
            try:
                values[match.group(1).lower()] = float(match.group(2))
            except ValueError:
                continue
    return values


def derive_parameters(prm_values, downsample, corr_filter_width):
    aliases = {
        "wavelength": ("radar_wavelength", "wavelength"),
        "near_range": ("near_range",),
        "earth_radius": ("earth_radius",),
        "SC_height": ("sc_height",),
        "SC_vel": ("sc_vel",),
        "rng_samp_rate": ("rng_samp_rate",),
        "PRF": ("prf",),
    }
    required = {}
    for name, candidates in aliases.items():
        for candidate in candidates:
            if candidate in prm_values:
                required[name] = prm_values[candidate]
                break
        else:
            raise ValueError("missing required PRM key: " + " or ".join(candidates))

    for key, value in required.items():
        if not math.isfinite(value) or value <= 0:
            raise ValueError("invalid PRM value for %s: %s" % (key, value))

    earth_radius = required["earth_radius"]
    orbit_radius = earth_radius + required["SC_height"]
    range_resolution = C / (2.0 * required["rng_samp_rate"])
    azimuth_resolution = (
        required["SC_vel"] * earth_radius / orbit_radius / required["PRF"]
    )
    return {
        "LAMBDA": required["wavelength"],
        "NEARRANGE": required["near_range"],
        "EARTHRADIUS": earth_radius,
        "ORBITRADIUS": orbit_radius,
        "DR": range_resolution * downsample,
        "DA": azimuth_resolution * downsample,
        "RANGERES": range_resolution,
        "AZRES": azimuth_resolution,
        "NLOOKSRANGE": downsample,
        "NLOOKSAZ": downsample,
        "NLOOKSOTHER": 1,
        "NCORRLOOKS": 4.0 * math.pi * (corr_filter_width / 6.0) ** 2,
    }


def format_value(value):
    if isinstance(value, int):
        return str(value)
    return format(value, ".12g")


def generate(base, prm, downsample, corr_filter_width, out):
    prm_values = read_prm(prm)
    parameters = derive_parameters(prm_values, downsample, corr_filter_width)
    base_text = base.read_text(encoding="utf-8", errors="replace")

    lines = base_text.splitlines(keepends=True)
    rendered = []
    written = set()
    disabled = {"NCORRLOOKSRANGE", "NCORRLOOKSAZ"}
    for line in lines:
        match = CONF_LINE.match(line)
        if not match:
            rendered.append(line)
            continue
        key = match.group(1).upper()
        if key in parameters:
            if key not in written:
                rendered.append("%s\t%s\n" % (key, format_value(parameters[key])))
                written.add(key)
        elif key in disabled:
            rendered.append("# " + line if not line.lstrip().startswith("#") else line)
        else:
            rendered.append(line)

    for key, value in parameters.items():
        if key not in written:
            rendered.append("%s\t%s\n" % (key, format_value(value)))

    header = [
        "# Auto-generated by snaphu_conf_gen.py",
        "# Source PRM: %s" % prm.resolve(),
        "# Derived values: " + " ".join(
            "%s=%s" % (key, format_value(value))
            for key, value in parameters.items()
        ),
        "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(header) + "\n" + "".join(rendered), encoding="utf-8")
    return parameters


def positive_int(value):
    parsed = int(value)
    if parsed <= 0:
        raise argparse.ArgumentTypeError("must be a positive integer")
    return parsed


def positive_float(value):
    parsed = float(value)
    if not math.isfinite(parsed) or parsed <= 0:
        raise argparse.ArgumentTypeError("must be a positive finite number")
    return parsed


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", required=True, type=Path)
    parser.add_argument("--prm", required=True, type=Path)
    parser.add_argument("--downsample", required=True, type=positive_int)
    parser.add_argument("--corr-filter-width", required=True, type=positive_float)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv)

    try:
        parameters = generate(
            args.base,
            args.prm,
            args.downsample,
            args.corr_filter_width,
            args.out,
        )
    except (OSError, ValueError) as exc:
        print("snaphu_conf_gen.py: %s" % exc, file=sys.stderr)
        return 1

    print(json.dumps(parameters, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
